      <p>
        AI開発ツールの進化は目まぐるしいが、その現在地を一本の軸で整理すると、次の行き先が見えてくる。それが<strong>組織のデジタルツイン</strong>だ。この記事では、その正体と、いま何をすべきかを論じる。
      </p>

      <AnchorH2 id="current-state">現在地 — AIに渡すものは一段ずつ大きくなってきた</AnchorH2>
      <p>
        AI開発ツールの流行は、プロンプト、ハーネス、ループと移り変わってきた。プロンプトは指示文そのもの、ハーネスは道具と権限を与える実行環境（Claude
        Code など）、ループは計画 → 実行 →
        検証を自己反復する工程（エージェント）だ。一見バラバラの流行に見えるが、一本の軸で説明できる。<strong>AIに渡すものが、指示文から実行環境、工程へと、一段ずつ大きくなっている</strong>のだ。
      </p>

      <EvolutionRailDiagram />

      <p>
        次に足りないのは<strong>記憶</strong>だ。ループはセッション内で閉じていて、「前回何をやったか」「組織として何を学んだか」が蓄積されない。だから毎セッション、同じ説明と同じ調査をやり直している。セッションを跨いで積み上がる層ができると、AIが参照する「部分的な世界の写像」が生まれ始める。それを組織全体に拡張したものが<strong>デジタルツイン</strong>だ。
      </p>

      <AnchorH2 id="what-is-digital-twin">デジタルツインとは何か、なぜ効くのか</AnchorH2>
      <p>
        ここで言うデジタルツインは、工場のセンサー模型のことではない。<strong>組織のドメイン知識・意思決定・運用実態を、機械が推論できる形に外部化したもの</strong>を指す。
      </p>
      <p>
        丁寧なドキュメント文化と何が違うのか。<strong>読み手</strong>だ。人間は行間を補って読んでくれるが、AIには書かれたものがすべて。だから暗黙の前提や判断の理由まで書き下し、書いたものを現実と同期させ続けることが要件になる。
      </p>
      <p>
        なぜこれが競争力になるのか。AI活用を構成する要素を「時間とともに一般化されるもの」と「組織に固有のもの」に分けると見えてくる。
      </p>

