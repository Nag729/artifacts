      <p>
        一般化される側で競っても、長期的には差がつかない。<strong>差がつくのは、組織固有の現実をどれだけ忠実に写像できているか</strong>だ。モデルが賢くなるほど一般化される側はコモディティ化し、組織固有の写像＝ツインを持つ者が有利になる。実際、企業のAI導入が失敗する主因はモデルの能力不足ではなく、この組織的コンテキストの欠如にあるという指摘が増えている。
      </p>

      <AnchorH2 id="objection">「賢いAIが自分で漁ればいい」への応答</AnchorH2>
      <p>
        ここで一つ、有力な反論を検討したい。モデルが賢くなれば、エージェントが自分でコードベース・チャットログ・ドキュメントを探索して文脈を獲得できるようになる。ならば、わざわざツインを作り込む必要などないのではないか？
      </p>
      <p>
        この反論は半分正しい。<strong>記録としてすでに存在する情報</strong>の復元は、確かにコモディティ化していく。散らかったログから文脈を掘り起こす能力は上がり続けるので、「既存の情報をきれいに整形・構造化しておく」タイプの投資は減価していく。
      </p>
      <p>
        しかし、どんなに賢いエージェントも<strong>記録されていないものは漁れない</strong>。そして組織で一番価値のある文脈は、たいていデジタル空間には存在しない。
      </p>

      <RecordedIcebergDiagram />

      <p>水面下の3つは、それぞれ理由が異なる。</p>
      <ul>
        <li>
          <strong>意思決定の Why</strong> —
          重要な議論ほど口頭で交わされ、記録には結論だけが残る。「なぜそうしたか」「何を却下したか」は、その場で書き残さない限り消える。
        </li>
        <li>
          <strong>現場の運用実態</strong> —
          マニュアルと実運用は必ず乖離する。そしてその乖離こそが知識なのに、誰かが観測してエンコードしないと情報として生まれない。
        </li>
        <li>
          <strong>判断基準（evals）</strong> —
          「何が正解か」は事実の集積から導けない規範であり、過去ログをいくら探索しても出てこない。
        </li>
      </ul>
      <p>
        つまりツインの本質は「検索を速くするキャッシュ」ではなく、<strong>そもそもデジタル空間に存在しない情報をAIリーダブルに変換する行為</strong>だ。前者はモデルの進化で代替されるが、後者は原理的に代替されない。堀として残るのは、記録に存在しないものを捕捉し続ける仕組みの方だ。
      </p>

      <AnchorH2 id="three-layers">何を写像するか — 3つのレイヤー</AnchorH2>
      <p>
        具体的に考えるため、題材を架空の物流向けSaaS——倉庫・配送業務の管理システム——に置いてみる。写像すべき対象は3層に分かれる。
      </p>
      <MappingLayersDiagram />

      <p>
        <strong>プロダクト</strong
        >レイヤーは、ドメインモデル・設計判断・仕様の意図。元々「現実をモデルに写像する」営みである
        DDD
        と、そのまま重なるレイヤーだ。<strong>チーム</strong>レイヤーは、意思決定の経緯・レビュー観点・暗黙の運用知識。意思決定ログや
        ADR
        が開発フローの副産物として溜まる仕組みが器になる。そして<strong>顧客</strong>レイヤーには、荷主ごとの暗黙の取り決め・倉庫ごとに異なる現場オペレーション・ドライバーの労働時間規制のような制度の制約が属する。
      </p>
      <p>
        このうち最重要なのは<strong>顧客レイヤー</strong>だ。プロダクトやチームの知識は、時間をかければ競合も似たものを構築できる。しかし顧客の現場で観測した運用実態は、その顧客と向き合った者にしか写像できない。最も模倣困難で、競合が持てない。プロダクトの堀そのものだ。
      </p>

      <Alert type="warning" title="最重要の設計原則">
        勝敗を分けるのは網羅性ではなく<strong>更新され続ける仕組み</strong>。ツインは作った瞬間から現実と乖離し始める。静的なドキュメント整備として始めると、更新が現実に追いつかず形骸化しやすい。日常の開発・運用フローの<strong>副産物</strong>として更新される設計にする。前章の結論——堀になるのは、記録に存在しないものを捕捉し続ける仕組みの方——がそのままこの原則の理由になる。
      </Alert>

      <AnchorH2 id="prior-art">参考になる先行事例</AnchorH2>
      <p>
        写像すべき対象と設計原則はわかった。では、実際にどう作るか。組織を機械可読にする試み自体は新しくないので、先人の試みから借りられるものを三つ挙げる。
      </p>
      <ul>
        <li>
          <strong>Palantir Ontology → 思想を借りる。</strong>Palantir
          社が提供する、企業のデータと業務を「オブジェクト＋リンク＋アクション」の形で統合的に表現する基盤で、組織のツインの最成熟実例と言える。その構造は、DDD
          のドメインモデリングを全社スケールに広げたものと見ることもできる。
        </li>
        <li>
          <strong>プロセスマイニング → 更新原理を借りる。</strong
          >業務システムのイベントログから、実際の業務フローを復元する分析手法。「あるべき姿（assumed）」ではなく「観測された振る舞い（observed）」から継続的に更新するという原理が、ツインの鮮度を保つ設計にそのまま使える。
        </li>
        <li>
          <strong>IaC / GitOps → 到達点の実例と見る。</strong>Git
          リポジトリ上の宣言的な定義を「正」とし、現実のインフラをそれに一致させ続ける運用手法。写像が原本になり、現実がデプロイ先になる——この主従逆転は次章で扱う進化の後半段階だが、インフラ領域ではすでに日常になっている実例だ。宣言と現実の乖離を検知して自動修復する仕組みも、ツインと現実を同期させ続ける設計の参考になる。
        </li>
      </ul>

      <AnchorH2 id="beyond-twin">ツインの先 — 写像は規範になる</AnchorH2>
      <p>
        ここまでは、写像を「作る」話をしてきた。だが写像には、作った先の段階がある。ツインは終着点ではない。
      </p>

      <MirrorStagesDiagram />

      <p>
        いま語られているツインは、ほぼ<strong>写像</strong>——現実を読み取り専用で写す段階だ。<strong>模擬</strong>に進むと、ツイン上で「もしこうしたら」を先に実行できるようになり、意思決定が予測から事前検証に変わる。<strong>操作</strong>ではツインへの書き込みが現実を動かすようになり、主従が逆転する——ツインが正、現実がデプロイ先だ。そして<strong>自律</strong>では、ツイン＋エージェントが日常運転を回し、人間は目的関数と制約の設定者に退く。
      </p>
      <p>
        操作の段階に至ると、「ツイン（双子）」という名前は不適切になる。双子ではなく<strong>原本</strong>になるからだ。事実を記述する「地図」が、規範を定める「法典」に変わる瞬間と言える。
      </p>
      <p>ただし、この進化には2つの原理的限界がある。</p>
      <p>
        <strong>限界1：完全な写像は原理的に作れない。</strong
        >ボルヘスの掌編「学問の厳密さについて」には、精密さを追求するあまり帝国と同じ縮尺になった地図が登場する。現実と同じ大きさの地図は、地図として機能しない。写像は常に取捨選択を含み、何かを必ず取りこぼす。
      </p>
      <p>
        <strong>限界2：ツインが規範化するとグッドハートの法則が発動する。</strong
        >「指標が目標になると、良い指標ではなくなる」——ツインに映るものだけが最適化され、映らない暗黙知が死んでいく。
      </p>
      <p>
        だから最終段階に至っても、「ツインと現実の乖離を検知して修正する人間」の役割は消えない。むしろ、そこが最後に残る仕事になる。
      </p>

      <AnchorH2 id="human-role">人の役割 — 現実を構造に翻訳する仕事</AnchorH2>
      <p>
        IT革命で希少になったのは「手続きをコードに翻訳できる人」で、それがソフトウェアエンジニアになった。コード翻訳が一般化される側に移った後、次に希少になるのは<strong>現実を構造に翻訳できる人</strong>だ。ドメインの暗黙知や制度の制約を、機械が推論可能な形にエンコードする役割である。
      </p>

      <TranslationFlowDiagram />

      <p>
        これは歴史的には二度目の登場でもある。1980年代のエキスパートシステム・ブームには「ナレッジエンジニア」という職業が実在した。当時は知識の受け皿である推論エンジンが弱すぎて消えたが、LLMで受け皿側が解決したいま、同じ職能が桁違いのレバレッジを持って戻ってくる。
      </p>
      <p>
        中核スキルはコーディング力ではなく<strong>モデリング力と越境力</strong>——現場の言葉を聞いて構造に落とす力だ。そしてツインは組織ごとに固有で複製できないため、需要はプロダクト企業に集中せず各組織に分散する。エンジニアより会計士や法務に近い、「どの組織にも一人ずつ要る」タイプの職業分布になる可能性がある。
      </p>

      <AnchorH2 id="conclusion">結論 — いま何をするか</AnchorH2>
      <ul>
        <li>
          <strong>降りる</strong> —
          効率競争から降りる。開発ツールの使いこなしの精緻化は減価償却が速く、モデルの進化は全員を平等に速くする。
        </li>
        <li>
          <strong>積む</strong> —
          組織固有の写像に投資する。設計判断・ドメイン知識・運用実態。ADR一枚がツインのレンガ一個だ。
        </li>
        <li>
          <strong>着手</strong> — メモリ設計と組織固有の evals
          から始める。進化の系譜で次に来る層であり、ツインの部品でもある。
        </li>
      </ul>

