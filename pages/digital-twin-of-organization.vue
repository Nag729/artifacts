      <p>
        AI開発ツールの進化は目まぐるしいが、その現在地を一本の軸で整理すると、次の行き先が見えてくる。それが<strong>組織のデジタルツイン</strong>だ。この記事では、その正体と、いま何をすべきかを論じる。
      </p>

      <AnchorH2 id="current-state">現在地 — 進化の正体は「渡すものの次元上昇」</AnchorH2>
      <p>
        AI開発ツールの流行は、プロンプト、ハーネス、ループと移り変わってきた。プロンプトは指示文そのもの、ハーネスは道具と権限を与える実行環境（Claude
        Code など）、ループは計画 → 実行 →
        検証を自己反復する工程（エージェント）だ。一見バラバラの流行に見えるが、一本の軸で説明できる。<strong>AIに渡すコンテキストの構造化レベルが、一段ずつ上がっている</strong>のだ。
      </p>

      <EvolutionRailDiagram />

      <p>
        次に足りないのは<strong>記憶</strong>だ。ループはセッション内で閉じていて、「前回何をやったか」「組織として何を学んだか」が蓄積されない。セッションを跨いで積み上がる層ができると、AIが参照する「部分的な世界の写像」が生まれ始める。それを組織全体に拡張したものが<strong>デジタルツイン</strong>だ。
      </p>
      <p>
        ここで言う記憶には、事実の蓄積だけでなく<strong>組織固有の判断基準</strong>も含まれる。ループに組み込まれている検証——テスト・型チェック・lint——は汎用的な正しさを守るもので、すでにツール側に備わっている。一方、「この組織にとって何が正解か」という判断基準（evals）はどのツールにも備わっていない。チームの頭の中に暗黙的にあるだけで、誰かが外部化してはじめて機械が参照できる形になる。そしてこれはセッションを跨いで積み上がる組織資産、つまり記憶の層に属する。この区別は後で効いてくるので、覚えておいてほしい。
      </p>

      <AnchorH2 id="what-is-digital-twin">デジタルツインとは何か、なぜ効くのか</AnchorH2>
      <p>
        ここで言うデジタルツインは、工場のセンサー模型のことではない。<strong>組織のドメイン知識・意思決定・運用実態を、機械が推論できる形に外部化したもの</strong>を指す。
      </p>
      <p>
        なぜこれが競争力になるのか。AI活用を構成する要素を「時間とともに一般化されるもの」と「組織に固有のもの」に分けると見えてくる。
      </p>

