      <p>
        一般化される側で競っても、長期的には差がつかない。<strong>差がつくのは、組織固有の現実をどれだけ忠実に写像できているか</strong>だ。
      </p>

      <AnchorH2 id="objection">「賢いAIが自分で漁ればいい」への応答</AnchorH2>
      <p>
        ここで一つ、有力な反論を検討したい。モデルが賢くなれば、エージェントが自分でコードベース・チャットログ・ドキュメントを探索して文脈を獲得できるようになる。ならば、わざわざツインを作り込む必要などないのではないか？
      </p>
      <p>
        この反論は半分正しい。<strong>記録としてすでに存在する情報</strong>の復元は、確かにコモディティ化していく。だから「既存の情報をきれいに整形・構造化しておく」タイプの投資は減価していく。
      </p>
      <p>
        しかし、どんなに賢いエージェントも<strong>記録されていないものは漁れない</strong>。そして組織の文脈は、価値のあるものほど記録から漏れやすい。
      </p>

      <RecordedIcebergDiagram />

      <p>水面下の3つは、それぞれ理由が異なる。</p>
      <ul>
        <li>
          <strong>意思決定の Why</strong> —
          重要な議論ほど口頭で交わされ、記録には結論だけが残る。「なぜそうしたか」「何を却下したか」は、その場で書き残さない限り消える。
        </li>
        <li>
          <strong>現場の運用実態</strong> —
          マニュアルと実運用は必ず乖離する。そしてその乖離こそが知識なのに、誰かが観測してエンコードしないと情報として生まれない。
        </li>
        <li>
          <strong>判断基準（evals）</strong> —
          「この組織にとって何が正解か」を定義した評価基準。これは探索して見つけるものではなく、<strong>決める</strong>ものだ。事実の集積からは導けない。
        </li>
      </ul>
      <p>
        つまりツインの本質は「検索を速くするキャッシュ」ではなく、<strong>そもそもデジタル空間に存在しない情報をAIリーダブルに変換する行為</strong>だ。前者はモデルの進化で代替されるが、後者は原理的に代替されない。
      </p>

      <AnchorH2 id="three-layers">何を写像するか — 3つの領域</AnchorH2>
      <p>
        具体的に考えるため、題材を架空の物流向けSaaS——倉庫・配送業務の管理システム——に置いてみる。写像すべき対象は3つの領域に分かれる。
      </p>
      <MappingLayersDiagram />

      <p>
        <strong>プロダクト</strong
        >領域は、ドメインモデル・設計判断・仕様の意図。元々「現実をモデルに写像する」営みである DDD
        と、そのまま重なる領域だ。<strong>チーム</strong>領域は、意思決定の経緯・レビュー観点・暗黙の運用知識。意思決定ログや
        ADR
        が開発フローの副産物として溜まる仕組みが器になる。そして<strong>顧客</strong>領域には、荷主ごとの暗黙の取り決め・倉庫ごとに異なる現場オペレーション・ドライバーの労働時間規制のような制度の制約が属する。
      </p>
      <p>
        このうち最重要なのは<strong>顧客領域</strong>だ。その理由は、顧客の現場の写像を持たない競合は、プロダクトを現場に適合させきれないからだ。具体的で、かつ包括的な現場の写像を持つことが、競争力の源泉になる。
      </p>
      <p>
        では、顧客の現場をどうやって写像するか。材料は日々流れ込んでいる——CS
        への問い合わせ、商談やオンボーディングの議事録、障害対応の記録。ただし、ログを溜めること自体に価値はない。それは水面の上に浮いているだけだ。ログの背後にある運用実態を読み取り、言語化する。この<strong>裁定</strong>こそが、顧客領域の写像を作る本質的な仕事になる。
      </p>

      <Alert type="warning" title="最重要の設計原則">
        勝敗を分けるのは一時的な網羅性ではなく<strong>更新され続けること</strong>。ツインは作った瞬間から現実と乖離し始めるため、静的なドキュメント整備として始めると、更新が現実に追いつかず形骸化する。日常の開発・運用フローの<strong>副産物</strong>として更新される設計にする。書き残しを支えるツール自体は、いずれ全員に配られる。配られないのは、何を書き残すべきかという判断と、積み上がった写像の方だ。
      </Alert>

      <AnchorH2 id="prior-art">参考になる先行事例</AnchorH2>
      <p>
        写像すべき対象と設計原則はわかった。では、実際にどう作るか。組織を機械可読にする試み自体は新しくないので、先人の試みから借りられるものを三つ挙げる。
      </p>
      <ul>
        <li>
          <strong>Palantir Ontology → 思想を借りる。</strong
          >企業のデータと業務を「オブジェクト＋リンク＋アクション」で表現する基盤で、組織のツインの最成熟実例。先ほどの物流SaaSなら、荷主・倉庫・配送便をオブジェクトに、荷主と倉庫の間の取り決めをリンクに、配車の変更をアクションに対応づけるイメージだ。DDD
          のドメインモデリングを全社スケールに広げたもの、と見ることもできる。
        </li>
        <li>
          <strong>プロセスマイニング → 更新原理を借りる。</strong
          >業務システムのイベントログから、実際の業務フローを復元する分析手法。「あるべき姿（assumed）」ではなく「観測された振る舞い（observed）」から継続的に更新するという原理が、ツインの鮮度を保つ設計にそのまま使える。
        </li>
        <li>
          <strong>IaC / GitOps → 同期の仕組みを借りる。</strong>Git
          リポジトリ上の宣言的な定義を「正」とし、現実のインフラをそれに一致させ続ける運用手法。宣言と現実の乖離を検知して自動修復する仕組みが、ツインを現実と同期させ続ける設計の参考になる。
        </li>
      </ul>

      <AnchorH2 id="beyond-twin">ツインの先 — 写像は規範になる</AnchorH2>
      <p>
        ここまでは、写像を「作る」話をしてきた。だが写像には、作った先の段階がある。ツインは終着点ではない。
      </p>

      <MirrorStagesDiagram />

      <p>
        いま語られているツインは、ほぼ<strong>写像</strong>の段階にある。<strong>模擬</strong>に進むと、意思決定は予測から事前検証に変わる。<strong>操作</strong>では書き込みが現実を動かし、主従が逆転する——ツインが正、現実がデプロイ先だ。この逆転は、インフラ領域では
        IaC / GitOps
        がすでに日常にしている。<strong>自律</strong>まで進めば日常運転はツインとエージェントが回し、人間は目的関数と制約の設定者に退く。
      </p>
      <p>
        操作の段階に至ると、「ツイン（双子）」という名前は不適切になる。双子ではなく<strong>原本</strong>になるからだ。事実を記述する「地図」が、規範を定める「法典」に変わる瞬間と言える。
      </p>
      <p>ただし、この進化には2つの原理的限界がある。</p>
      <p>
        <strong>限界1：完全な写像は原理的に作れない。</strong
        >ボルヘスの掌編「学問の厳密さについて」には、精密さを追求するあまり帝国と同じ縮尺になった地図が登場する。現実と同じ大きさの地図は、地図として機能しない。写像は常に取捨選択を含み、何かを必ず取りこぼす。
      </p>
      <p>
        <strong>限界2：ツインが規範化するとグッドハートの法則が発動する。</strong
        >「指標が目標になると、良い指標ではなくなる」——ツインに映るものだけが最適化され、映らない暗黙知が死んでいく。
      </p>
      <p>
        だから最終段階に至っても、「ツインと現実の乖離を検知して修正する人間」の役割は消えない。むしろ、そこが最後に残る仕事になる。
      </p>

      <AnchorH2 id="human-role">人の役割 — 現実を構造に翻訳する仕事</AnchorH2>
      <p>
        IT革命で希少になったのは「手続きをコードに翻訳できる人」で、それがソフトウェアエンジニアになった。コード翻訳が一般化される側に移った後、次に希少になるのは<strong>現実を構造に翻訳できる人</strong>だ。ドメインの暗黙知や制度の制約を、機械が推論可能な形にエンコードする役割である。
      </p>

      <TranslationFlowDiagram />

      <p>
        これは歴史的には二度目の登場でもある。1980年代のエキスパートシステム・ブームには「ナレッジエンジニア」という職業が実在した。当時は知識の受け皿である推論エンジンが弱すぎて消えたが、LLMという強力な受け皿を得たいま、同じ職能が桁違いのレバレッジを持って戻ってくる。
      </p>
      <p>
        中核スキルはコーディング力ではなく<strong>モデリング力と越境力</strong>——現場の言葉を聞いて構造に落とす力だ。そしてツインは組織ごとに固有で複製できないため、需要はプロダクト企業に集中せず各組織に分散する。エンジニアより会計士や法務に近い、「どの組織にも一人ずつ要る」タイプの職業分布になる可能性がある。
      </p>

      <AnchorH2 id="conclusion">結論 — いま何をするか</AnchorH2>
      <ul>
        <li>
          <strong>競わない</strong> —
          効率競争で差別化しない。使いこなしの精緻化は減価が速く、モデルの進化は全員を平等に速くする。
        </li>
        <li>
          <strong>積む</strong> — 組織固有の写像に投資する。開発側は記憶の設計と組織固有の
          evals、顧客側は問い合わせや議事録からの運用実態の書き下し。ADR一枚がツインのレンガ一個だ。
        </li>
        <li>
          <strong>回す</strong> —
          一度きりの棚卸しプロジェクトにしない。ツインを日常の開発・運用フローの副産物にする。
        </li>
      </ul>

